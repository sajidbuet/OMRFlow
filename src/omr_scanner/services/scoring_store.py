class ScoringError(OMRScannerError):
    """A scoring or answer-key operation was refused.

    Always carries a ``user_message``: an operator is mid-task and needs to
    know what to do differently.
    """


def _now() -> datetime:
    """The current instant, timezone-aware."""
    return datetime.now(UTC)


def _dump_numbers(numbers: Iterable[int]) -> str:
    """Serialise a set of question numbers for storage."""
    return ",".join(str(number) for number in sorted(set(numbers)))


def _load_numbers(payload: str) -> frozenset[int]:
    """Read a stored set of question numbers."""
    return frozenset(
        int(chunk) for chunk in payload.split(",") if chunk.strip().isdigit()
    )



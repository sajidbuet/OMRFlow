def _to_key(row: AnswerKeyRevision) -> AnswerKey:
    """Convert a stored revision into a detached domain key."""
    return AnswerKey(
        set_code=row.set_code,
        answers=row.answers,
        wrong_questions=_load_numbers(row.wrong_questions),
        revision=row.revision,
        first_question=row.first_question,
        status=AnswerKeyStatus(row.status),
        source=AnswerKeySource(row.source),
    )


@dataclass(frozen=True, slots=True)
class StoredKey:
    """One answer-key revision, with the row id a result references.

    The provenance fields (``created_by`` onward) are empty on a revision
    stored before migration 12; nothing fills them in retrospectively.
    """

    key_id: int
    key: AnswerKey
    created_at: datetime
    verified_at: datetime | None = None
    verified_by: str = ""
    source_scan: str = ""
    notes: str = ""
    created_by: str = ""
    template_id: str = ""
    template_name: str = ""
    template_fingerprint: str = ""
    source_sha256: str = ""
    source_metadata: dict[str, Any] = field(default_factory=dict)

    @property
    def set_code(self) -> str:
        """Which paper this answers."""
        return self.key.set_code

    @property
    def revision(self) -> int:
        """Which revision this is."""
        return self.key.revision

    def describe(self) -> str:
        """A one-line summary for a list."""
        return self.key.describe()


def _load_metadata(payload: str) -> dict[str, Any]:
    """Read a stored metadata blob; a damaged one reads as empty, never raises."""
    if not payload:
        return {}
    try:
        value = json.loads(payload)
    except ValueError:
        return {}
    return value if isinstance(value, dict) else {}


def _stored(row: AnswerKeyRevision) -> StoredKey:
    return StoredKey(
        key_id=row.key_id,
        key=_to_key(row),
        created_at=row.created_at,
        verified_at=row.verified_at,
        verified_by=row.verified_by,
        source_scan=row.source_scan,
        notes=row.notes,
        created_by=row.created_by,
        template_id=row.template_id,
        template_name=row.template_name,
        template_fingerprint=row.template_fingerprint,
        source_sha256=row.source_sha256,
        source_metadata=_load_metadata(row.source_metadata_json),
    )


def save_key(
    database: ProjectDatabase,
    key: AnswerKey,
    *,
    source_scan: str = "",
    notes: str = "",
    created_by: str = "",
    template: OmrTemplate | None = None,
    source_sha256: str = "",
    source_metadata: dict[str, Any] | None = None,
) -> StoredKey:
    """Store a new draft revision of a set's answer key.

    Args:
        database: The open project database.
        key: The key to store. Its ``revision`` is **ignored** and recomputed -
            the store owns revision numbering, so two operators cannot create
            two "revision 2"s.
        source_scan: The solution sheet's file name, when the key was read from
            one. A name, not a path.
        notes: Free text.
        created_by: Who entered or imported the key.
        template: The template the key was written against; its id, name and
            geometry fingerprint are recorded so a later template change can be
            recognised.
        source_sha256: SHA-256 of the solution-sheet image, when there is one.
            Recorded because the file may later be moved or deleted.
        source_metadata: JSON-serialisable facts about how a scanned key was
            read (registration, set-code check, questions corrected by hand).

    Returns:
        The stored revision, with the id a result will reference.

    A new revision is always created. Editing a stored revision in place would
    silently change what an existing result was computed from, which is the one
    thing Phase 8 must never do.

    Revisions are numbered per **logical** set: a revision stored earlier under
    ``"a"`` and one stored now under ``"A"`` are revisions 1 and 2 of one set.
    The code is stored as given; it is compared canonically.
    """
    with database.session() as session:
        highest = max(
            (
                int(revision)
                for code, revision in session.execute(
                    select(AnswerKeyRevision.set_code, AnswerKeyRevision.revision)
                ).all()
                if same_set(code, key.set_code)
            ),
            default=0,
        )
        revision = highest + 1
        row = AnswerKeyRevision(
            set_code=key.set_code,
            revision=revision,
            answers=key.answers,
            wrong_questions=_dump_numbers(key.wrong_questions),
            first_question=key.first_question,
            question_count=key.question_count,
            status=AnswerKeyStatus.DRAFT.value,
            source=key.source.value,
            source_scan=source_scan,
            notes=notes,
            created_at=_now(),
            created_by=created_by.strip(),
            template_id=template.template_id if template is not None else "",
            template_name=template.name if template is not None else "",
            template_fingerprint=(
                template.geometry_fingerprint() if template is not None else ""
            ),
            source_sha256=source_sha256,
            source_metadata_json=(
                json.dumps(source_metadata, sort_keys=True) if source_metadata else ""
            ),
        )
        session.add(row)
        session.flush()
        stored = _stored(row)

    _LOGGER.info(
        "Answer key saved: set=%s revision=%d questions=%d wrong=%d source=%s",
        key.set_code,
        revision,
        key.question_count,
        len(key.wrong_questions),
        key.source.value,
    )
    return stored


def verify_key(
    database: ProjectDatabase,
    key_id: int,
    *,
    verified_by: str,
    plan: QuestionPlan | None = None,
) -> StoredKey:
    """Mark one revision verified, superseding the set's previous verified one.

    Args:
        database: The open project database.
        key_id: The revision to verify.
        verified_by: Who checked it. Required - a key is the standard every
            candidate is measured against, and an unattributed one is not a
            standard.
        plan: The active template's questions. When given, a revision that no
            longer fits it (see
            :func:`~omr_scanner.services.answer_key.compatibility_issues`) is
            refused: verifying a key for a different paper would let it mark
            candidates.

    Raises:
        ScoringError: No such revision, no name given, the revision is already
            superseded, or it does not fit ``plan``.

    Superseding rather than deleting: results computed under the previous
    revision still point at it, and must still be able to say what they were
    computed from.
    """
    name = verified_by.strip()
    if not name:
        raise ScoringError(
            "No verifier name",
            user_message=(
                "Set your name in File > Settings > Reviewer before verifying "
                "an answer key. A verified key is recorded against the person "
                "who checked it."
            ),
        )
    identity = set_identity.load(database)
    with database.session() as session:
        row = session.get(AnswerKeyRevision, key_id)
        if row is None:
            raise ScoringError(
                f"Answer key {key_id} not found",
                user_message="That answer key is no longer in this project.",
            )
        if row.status == AnswerKeyStatus.SUPERSEDED.value:
            raise ScoringError(
                "Refusing to verify a superseded revision",
                user_message=(
                    f"Set {row.set_code} revision {row.revision} has been "
                    "replaced by a later revision and cannot be verified again."
                ),
            )
        if plan is not None:
            problems = compatibility_issues(_to_key(row), plan)
            if problems:
                raise ScoringError(
                    "Refusing to verify a key that does not fit the template",
                    user_message=(
                        f"Set {row.set_code} revision {row.revision} does not fit "
                        f"the active template: {problems[0]}"
                    ),
                )
        set_identity.require_no_collision(
            identity, purpose="Verifying this answer key", codes=(row.set_code,)
        )
        for other in session.scalars(
            select(AnswerKeyRevision)
            .where(AnswerKeyRevision.status == AnswerKeyStatus.VERIFIED.value)
            .where(AnswerKeyRevision.key_id != key_id)
        ).all():
            # One verified revision per *logical* set, whatever spelling an
            # earlier revision was stored under.
            if same_set(other.set_code, row.set_code):
                other.status = AnswerKeyStatus.SUPERSEDED.value
        row.status = AnswerKeyStatus.VERIFIED.value
        row.verified_at = _now()
        row.verified_by = name
        stored = _stored(row)

    _LOGGER.info(
        "Answer key verified: set=%s revision=%d", stored.set_code, stored.revision
    )
    return stored


def verified_key(database: ProjectDatabase, set_code: str) -> StoredKey | None:
    """Return the verified key for one set, or ``None``.

    Compared canonically, so a key stored as ``"a"`` is Set ``A``'s - the
    lookup that once upper-cased only one side (defect 5 of
    ``0.1.0-alpha.2``).
    """
    return verified_keys(database).get(set_code)


def verified_keys(database: ProjectDatabase) -> SetCodeMap[StoredKey]:
    """Return every set's verified key, keyed by set code, compared canonically.

    ``keys.get("a")`` finds a key stored under ``"A"``. Should two verified
    revisions of one logical set exist - possible only in data written before
    canonical identity, under two spellings - the most recently verified wins
    and the other is listed in :attr:`~omr_scanner.domain.set_identity.SetCodeMap.shadowed`;
    :func:`verify_key` now supersedes across spellings, so it cannot recur.
    """
    with database.session() as session:
        rows = session.scalars(
            select(AnswerKeyRevision)
            .where(AnswerKeyRevision.status == AnswerKeyStatus.VERIFIED.value)
            .order_by(
                AnswerKeyRevision.verified_at.desc(),
                AnswerKeyRevision.revision.desc(),
                AnswerKeyRevision.key_id.desc(),
            )
        ).all()
        found = SetCodeMap((row.set_code, _stored(row)) for row in rows)
    # Iterated in set-code order, as the dictionary this replaces was.
    return SetCodeMap((code, found[code]) for code in sorted(found))


def get_key(database: ProjectDatabase, key_id: int) -> StoredKey | None:
    """Return one revision by id, whatever its status."""
    with database.session() as session:
        row = session.get(AnswerKeyRevision, key_id)
        return _stored(row) if row is not None else None


def list_keys(
    database: ProjectDatabase, *, set_code: str = ""
) -> tuple[StoredKey, ...]:
    """Return stored revisions, newest first, optionally for one set (canonically)."""
    with database.session() as session:
        rows = session.scalars(
            select(AnswerKeyRevision).order_by(
                AnswerKeyRevision.set_code, AnswerKeyRevision.revision.desc()
            )
        ).all()
        wanted = set_code.strip()
        return tuple(
            _stored(row) for row in rows if not wanted or same_set(row.set_code, wanted)
        )


def known_set_codes(database: ProjectDatabase) -> tuple[str, ...]:
    """Every set a key has been written for, one spelling per logical set."""
    with database.session() as session:
        return distinct_codes(
            sorted(
                {
                    value
                    for (value,) in session.execute(
                        select(AnswerKeyRevision.set_code).distinct()
                    ).all()
                }
            )
        )


class SetKeyState(StrEnum):
    """Whether one set has a key Results can mark with."""

    MISSING = "missing"
    """No revision has ever been stored for the set."""

    DRAFT = "draft"
    """Revisions exist, none verified. Results will not mark with it."""

    VERIFIED = "verified"
    """A verified revision that fits the active template."""

    STALE = "stale"
    """The revision that would be used no longer fits the active template."""

    @property
    def label(self) -> str:
        """Operator-facing wording."""
        return {
            SetKeyState.MISSING: "Missing",
            SetKeyState.DRAFT: "Draft",
            SetKeyState.VERIFIED: "Verified",
            SetKeyState.STALE: "Incompatible",
        }[self]


@dataclass(frozen=True, slots=True)
class SetKeyOverview:
    """One set's answer-key position, for the overview and the pre-Results check.

    Attributes:
        set_code: The set.
        state: See :class:`SetKeyState`.
        verified: The verified revision - the one Results marks with - if any.
        latest: The newest revision, whatever its status.
        issues: Why the revision that would be used does not fit the template.
    """

    set_code: str
    state: SetKeyState
    verified: StoredKey | None = None
    latest: StoredKey | None = None
    issues: tuple[str, ...] = ()

    @property
    def has_pending_draft(self) -> bool:
        """Whether a draft newer than the verified revision is waiting."""
        return (
            self.latest is not None
            and self.latest.key.status is AnswerKeyStatus.DRAFT
            and (self.verified is None or self.latest.revision > self.verified.revision)
        )

    @property
    def is_ready(self) -> bool:
        """Whether Results can mark this set's candidates."""
        return self.state is SetKeyState.VERIFIED

    def describe(self) -> str:
        """``"Set C: saved as a draft, not verified"``-style sentence."""
        name = f"Set {self.set_code}"
        if self.state is SetKeyState.MISSING:
            return f"{name}: no answer key."
        if self.state is SetKeyState.DRAFT:
            return f"{name}: answer key saved but not verified."
        if self.state is SetKeyState.STALE:
            reason = f" {self.issues[0]}" if self.issues else ""
            return f"{name}: answer key does not fit the active template.{reason}"
        pending = (
            f" (a newer draft, revision {self.latest.revision}, is not verified)"
            if self.has_pending_draft and self.latest is not None
            else ""
        )
        revision = self.verified.revision if self.verified is not None else 0
        return f"{name}: verified revision {revision}{pending}."


def key_overview(
    database: ProjectDatabase,
    set_codes: Sequence[str],
    plan: QuestionPlan | None,
) -> tuple[SetKeyOverview, ...]:
    """Every listed set's key position, in the order given.

    Read in one pass over the revisions. The key that *would* be used is the
    verified one when there is one, else the newest draft; it is that key
    which is checked against ``plan``, so a verified key that no longer fits
    reads as :attr:`SetKeyState.STALE` and is never reported as ready.

    Revisions are grouped by logical set, so a key stored as ``"a"`` counts
    for Set ``A``.
    """
    by_set = group_by_set((stored.set_code, stored) for stored in list_keys(database))

    overview: list[SetKeyOverview] = []
    for code in set_codes:
        revisions = by_set.get(code, [])
        if not revisions:
            overview.append(SetKeyOverview(code, SetKeyState.MISSING))
            continue
        latest = max(revisions, key=lambda item: item.revision)
        verified = max(
            (item for item in revisions if item.key.status is AnswerKeyStatus.VERIFIED),
            key=lambda item: item.revision,
            default=None,
        )
        used = verified or latest
        issues = compatibility_issues(used.key, plan) if plan is not None else ()
        if issues:
            state = SetKeyState.STALE
        elif verified is not None:
            state = SetKeyState.VERIFIED
        else:
            state = SetKeyState.DRAFT
        overview.append(SetKeyOverview(code, state, verified, latest, issues))
    return tuple(overview)



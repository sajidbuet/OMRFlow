"""Store answer keys, scoring policy and results - and recompute, never patch.

Purpose:
    The repository layer for Phase 8: answer-key revisions and their
    verification, scoring-policy revisions, and `CandidateResult` rows that
    identify exactly which of each produced them.

Scope:
    Database access. The arithmetic is in :mod:`omr_scanner.domain.scoring`,
    the eligibility rules in :mod:`omr_scanner.services.scoring`, and neither
    imports Qt.

Three arrangements that carry the phase:

**A revision is never edited.** Correcting a verified key that results already
reference creates the next revision and supersedes the old one; the old row
stays, because a result points at it. The same is true of the scoring policy.

**A result stores its inputs, not just its mark.** The answer string, the key
revision and the policy revision are all on the row, so the breakdown can be
regenerated by the same pure function that produced the total - which is why
there is no per-question table to fall out of step with it.

**Changing an input makes a result stale; it never changes the number.**
:func:`stale_reasons_for` compares what a result was computed from against what
is current, and :func:`score_batch` runs the whole scorer again from stored
inputs. Nothing in this module adds a delta to an existing mark.

Privacy:
    No candidate ID, name, answer string or mark is logged. Counts, revisions
    and roster/batch ids only - see ``docs/reconciliation.md`` §9.
"""


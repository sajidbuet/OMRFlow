# Scoring policy
# ----------------------------------------------------------------------
_POLICY_FIELDS = (
    "correct_mark",
    "blank_mark",
    "incorrect_penalty",
    "multiple_penalty",
    "mode",
    "clamp_minimum",
    "minimum_score",
)
"""Every score-affecting field. Changing any of them means a new revision."""


def _to_policy(row: ScoringPolicyRevision) -> ScoringPolicy:
    """Convert a stored revision into a detached domain policy."""
    return ScoringPolicy(
        correct_mark=Fraction(row.correct_mark),
        blank_mark=Fraction(row.blank_mark),
        incorrect_penalty=Fraction(row.incorrect_penalty),
        multiple_penalty=(
            Fraction(row.multiple_penalty) if row.multiple_penalty else None
        ),
        mode=NegativeMarking(row.mode),
        clamp_minimum=row.clamp_minimum,
        minimum_score=Fraction(row.minimum_score),
        revision=row.revision,
    )


@dataclass(frozen=True, slots=True)
class StoredPolicy:
    """One scoring-policy revision, with the row id a result references."""

    policy_id: int
    policy: ScoringPolicy
    created_at: datetime
    created_by: str = ""
    is_active: bool = True

    @property
    def revision(self) -> int:
        """Which revision this is."""
        return self.policy.revision


def _stored_policy(row: ScoringPolicyRevision) -> StoredPolicy:
    return StoredPolicy(
        policy_id=row.policy_id,
        policy=_to_policy(row),
        created_at=row.created_at,
        created_by=row.created_by,
        is_active=row.is_active,
    )


def _policy_columns(policy: ScoringPolicy) -> dict[str, Any]:
    """The stored form of a policy's score-affecting fields."""
    return {
        "correct_mark": str(policy.correct_mark),
        "blank_mark": str(policy.blank_mark),
        "incorrect_penalty": str(policy.incorrect_penalty),
        "multiple_penalty": (
            str(policy.multiple_penalty) if policy.multiple_penalty is not None else ""
        ),
        "mode": policy.mode.value,
        "clamp_minimum": policy.clamp_minimum,
        "minimum_score": str(policy.minimum_score),
    }


def active_policy(database: ProjectDatabase) -> StoredPolicy:
    """Return the policy in force, creating the default one if none exists.

    A project that has never been scored gets revision 1 with no negative
    marking - the most conservative rule, and the one least likely to be
    applied by accident.
    """
    with database.session() as session:
        row = session.scalars(
            select(ScoringPolicyRevision)
            .where(ScoringPolicyRevision.is_active.is_(True))
            .order_by(ScoringPolicyRevision.revision.desc())
            .limit(1)
        ).first()
        if row is not None:
            return _stored_policy(row)
        if database.read_only:
            # Phase 10, §42: a read-only session must never write, including
            # the conservative-default-on-first-read this function otherwise
            # performs. Return the same default values, unpersisted, so a
            # read-only open can still be inspected rather than failing here.
            return StoredPolicy(
                policy_id=0,
                policy=ScoringPolicy(),
                created_at=_now(),
                created_by="",
                is_active=True,
            )
        created = ScoringPolicyRevision(
            revision=1,
            created_at=_now(),
            is_active=True,
            **_policy_columns(ScoringPolicy()),
        )
        session.add(created)
        session.flush()
        return _stored_policy(created)


def save_policy(
    database: ProjectDatabase, policy: ScoringPolicy, *, created_by: str = ""
) -> StoredPolicy:
    """Store the policy, creating a new revision only if a rule changed.

    Returns:
        The policy now in force.

    Saving an unchanged policy is a no-op that returns the current revision.
    Creating a revision per click would make every result stale for no reason,
    and "stale" has to mean something for an operator to act on it.
    """
    proposed = _policy_columns(policy)
    with database.session() as session:
        current = session.scalars(
            select(ScoringPolicyRevision)
            .where(ScoringPolicyRevision.is_active.is_(True))
            .order_by(ScoringPolicyRevision.revision.desc())
            .limit(1)
        ).first()
        if current is not None and all(
            getattr(current, name) == proposed[name] for name in _POLICY_FIELDS
        ):
            return _stored_policy(current)

        highest = session.scalars(
            select(func.max(ScoringPolicyRevision.revision))
        ).first()
        if current is not None:
            current.is_active = False
        row = ScoringPolicyRevision(
            revision=int(highest or 0) + 1,
            created_at=_now(),
            created_by=created_by.strip(),
            is_active=True,
            **proposed,
        )
        session.add(row)
        session.flush()
        stored = _stored_policy(row)

    _LOGGER.info(
        "Scoring policy saved: revision=%d mode=%s clamp=%s",
        stored.revision,
        stored.policy.mode.value,
        stored.policy.clamp_minimum,
    )
    return stored


def get_policy(database: ProjectDatabase, policy_id: int) -> StoredPolicy | None:
    """Return one policy revision by id."""
    with database.session() as session:
        row = session.get(ScoringPolicyRevision, policy_id)
        return _stored_policy(row) if row is not None else None


def list_policies(database: ProjectDatabase) -> tuple[StoredPolicy, ...]:
    """Return every policy revision, newest first."""
    with database.session() as session:
        rows = session.scalars(
            select(ScoringPolicyRevision).order_by(
                ScoringPolicyRevision.revision.desc()
            )
        ).all()
        return tuple(_stored_policy(row) for row in rows)


# ----------------------------------------------------------------------
# Gathering a candidate's authoritative inputs
# ----------------------------------------------------------------------
@dataclass(frozen=True, slots=True)
class BatchInputs:
    """Everything a batch needs to be scored, read once.

    Read once rather than per candidate: ten thousand candidates would
    otherwise open ten thousand transactions and decode ten thousand results
    that are already in memory.
    """

    plan: QuestionPlan
    entries: tuple[ReconciliationEntry, ...]
    results: dict[int, ScanResult]
    answers: dict[int, CandidateAnswers]
    keys: dict[str, StoredKey]
    policy: StoredPolicy


def gather_inputs(
    database: ProjectDatabase,
    roster_id: int,
    batch_id: str,
    template: OmrTemplate,
) -> BatchInputs:
    """Read every authoritative input for a batch, once.

    The answers come through Phase 6's
    :func:`~omr_scanner.services.review_store.effective_answers` and
    :func:`~omr_scanner.services.review_store.effective_set_codes`, never from
    the recognition result alone: those hold what the *machine* read, and
    marking against them would ignore every correction a reviewer made.
    """
    plan = plan_for(template)
    entries = reconciliation_store.list_entries(database, roster_id, batch_id)
    results = batch_store.results_by_scan(database, batch_id)
    decisions = review_store.effective_answers(database, batch_id, template)
    set_codes = review_store.effective_set_codes(database, batch_id)

    answers: dict[int, CandidateAnswers] = {}
    for scan_id, result in results.items():
        decided = decisions.get(scan_id)
        found = set_codes.get(scan_id)
        answers[scan_id] = build_candidate_answers(
            result,
            plan,
            scan_id=scan_id,
            decided=decided.decided if decided else None,
            unresolved=decided.unresolved_questions if decided else (),
            set_code=found.value if found else "",
        )

    return BatchInputs(
        plan=plan,
        entries=entries,
        results=results,
        answers=answers,
        keys=verified_keys(database),
        policy=active_policy(database),
    )


def inputs_for_candidate(
    data: BatchInputs, entry: ReconciliationEntry
) -> ScoringInputs:
    """Assemble one candidate's scoring inputs from a batch's."""
    scan_id, _ = working_script(entry)
    answers = data.answers.get(scan_id) if scan_id is not None else None
    key = data.keys.get(answers.set_code) if answers and answers.set_code else None
    return ScoringInputs(
        entry=entry,
        answers=answers,
        key=key.key if key else None,
        policy=data.policy.policy,
        plan=data.plan,
    )


# ----------------------------------------------------------------------
# Scoring a batch
# ----------------------------------------------------------------------
def score_batch(
    database: ProjectDatabase,
    roster_id: int,
    batch_id: str,
    template: OmrTemplate,
    *,
    computed_by: str = "",
    candidates: Sequence[str] | None = None,
    should_cancel: Callable[[], bool] | None = None,
    on_progress: Callable[[int, int], None] | None = None,
) -> ResultCounts:
    """Score a batch - or the named candidates - from authoritative inputs.

    Args:
        database: The open project database.
        roster_id: The active candidate list.
        batch_id: The batch of scripts.
        template: The template the batch was read with.
        computed_by: Who ran the scoring, if known.
        candidates: Restrict to these candidate ids. ``None`` scores all of
            them.
        should_cancel: Polled between candidates.
        on_progress: Called with ``(done, total)``.

    Returns:
        The summary counts.

    **This is a recomputation, never a patch.** Every result is produced by
    running the scorer over the stored answer string, the stored set, the
    verified key and the active policy. No existing mark is read, adjusted or
    carried forward, so a corrupted stored score cannot survive a rescore - a
    property a test asserts directly by corrupting one.

    Results are written per candidate inside one transaction at the end, so a
    cancelled run leaves the previous results intact rather than a mixture.
    """
    data = gather_inputs(database, roster_id, batch_id, template)
    wanted = set(candidates) if candidates is not None else None
    targets = [
        entry
        for entry in data.entries
        if wanted is None or entry.candidate_id in wanted
    ]

    scored: list[tuple[ReconciliationEntry, CandidateScore]] = []
    total = len(targets)
    cancelled = False
    for index, entry in enumerate(targets, start=1):
        if should_cancel is not None and should_cancel():
            cancelled = True
            _LOGGER.info(
                "Scoring cancelled after %d of %d candidate(s); nothing written",
                index - 1,
                total,
            )
            break
        scored.append((entry, score_candidate(inputs_for_candidate(data, entry))))
        if on_progress is not None:
            on_progress(index, total)

    if cancelled:
        # Nothing is written. A half-marked batch under two policies, claiming
        # to be current, is worse than a batch that was never marked - and
        # "coherent after cancellation" is not something to approximate when
        # the numbers may end up on a transcript.
        return count_results(database, roster_id, batch_id)

    moment = _now()
    with database.session() as session:
        for entry, outcome in scored:
            _write_result(
                session,
                roster_id=roster_id,
                batch_id=batch_id,
                entry=entry,
                outcome=outcome,
                data=data,
                moment=moment,
                computed_by=computed_by,
            )

    counts = count_results(database, roster_id, batch_id)
    _LOGGER.info(
        "Scored: roster=%d candidates=%d scored=%d absent=%d blocked=%d policy_rev=%d",
        roster_id,
        len(scored),
        counts.scored,
        counts.absent,
        counts.blocked,
        data.policy.revision,
    )
    return counts


def _write_result(
    session: Session,
    *,
    roster_id: int,
    batch_id: str,
    entry: ReconciliationEntry,
    outcome: CandidateScore,
    data: BatchInputs,
    moment: datetime,
    computed_by: str,
) -> None:
    """Replace one candidate's stored result with a freshly computed one."""
    row = session.scalars(
        select(CandidateResult)
        .where(CandidateResult.roster_id == roster_id)
        .where(CandidateResult.batch_id == batch_id)
        .where(CandidateResult.candidate_id == entry.candidate_id)
        .limit(1)
    ).first()
    if row is None:
        row = CandidateResult(
            roster_id=roster_id,
            batch_id=batch_id,
            candidate_id=entry.candidate_id,
            created_at=moment,
            computed_at=moment,
        )
        session.add(row)

    answers = outcome.answers
    key_id = 0
    if outcome.key is not None:
        stored = data.keys.get(outcome.key.set_code)
        key_id = stored.key_id if stored else 0

    row.scan_id = answers.scan_id if answers else None
    row.set_code = outcome.set_code
    row.answer_string = answers.answers if answers else ""
    row.machine_answer_string = answers.machine_answers if answers else ""
    row.corrected_questions = _dump_numbers(answers.corrected) if answers else ""
    row.answer_key_id = key_id or None
    row.answer_key_revision = outcome.key.revision if outcome.key else 0
    row.policy_id = data.policy.policy_id
    row.policy_revision = data.policy.revision
    row.first_question = data.plan.first_question
    row.status = outcome.status.value
    row.blocks = "|".join(
        f"{item.reason.value}:{item.detail}" for item in outcome.blocks
    )
    row.stale_reasons = ""
    row.computed_at = moment
    row.computed_by = computed_by.strip()

    breakdown = outcome.breakdown
    if breakdown is not None:
        row.question_count = breakdown.question_count
        row.correct_count = breakdown.correct_count
        row.incorrect_count = breakdown.incorrect_count
        row.blank_count = breakdown.blank_count
        row.multiple_count = breakdown.multiple_count
        row.wrong_question_count = breakdown.wrong_question_count
        row.raw_score = str(breakdown.raw_score)
        row.final_score = str(breakdown.final_score)
        row.clamped = breakdown.clamped
    else:
        row.question_count = len(answers.answers) if answers else 0
        row.correct_count = row.incorrect_count = row.blank_count = 0
        row.multiple_count = row.wrong_question_count = 0
        row.raw_score = row.final_score = ""
        row.clamped = False



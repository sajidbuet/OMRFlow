@dataclass(frozen=True, slots=True)
class StoredResult:
    """One stored result, and the provenance that explains it."""

    result_id: int
    candidate_id: str
    display_name: str
    scan_id: int | None
    set_code: str
    status: ResultStatus
    answer_string: str
    machine_answer_string: str
    corrected_questions: frozenset[int]
    answer_key_id: int | None
    answer_key_revision: int
    policy_id: int | None
    policy_revision: int
    first_question: int
    question_count: int
    correct_count: int
    incorrect_count: int
    blank_count: int
    multiple_count: int
    wrong_question_count: int
    raw_score: Fraction | None
    final_score: Fraction | None
    clamped: bool
    blocks: tuple[ScoringBlock, ...]
    stale_reasons: tuple[StaleReason, ...]
    computed_at: datetime
    computed_by: str = ""

    @property
    def is_stale(self) -> bool:
        """Whether an input has changed since this was computed."""
        return bool(self.stale_reasons)

    @property
    def has_mark(self) -> bool:
        """Whether this result carries a numeric mark."""
        return self.status is ResultStatus.SCORED and self.final_score is not None

    def describe_stale(self) -> str:
        """Why this result needs recomputing."""
        if not self.stale_reasons:
            return ""
        return "Needs recomputing because " + ", and ".join(
            reason.label for reason in self.stale_reasons
        )

    def describe_blocks(self) -> str:
        """Why this candidate could not be scored."""
        return "; ".join(item.describe() for item in self.blocks)

    def describe_provenance(self) -> str:
        """The exact revisions that produced this mark."""
        if self.answer_key_revision:
            key = f"Set {self.set_code} / revision {self.answer_key_revision}"
        else:
            key = "no answer key"
        return f"Answer key: {key} · Scoring policy: revision {self.policy_revision}"


def _parse_blocks(payload: str) -> tuple[ScoringBlock, ...]:
    """Read stored block records."""
    blocks: list[ScoringBlock] = []
    for chunk in payload.split("|"):
        if not chunk:
            continue
        reason, _, detail = chunk.partition(":")
        try:
            blocks.append(ScoringBlock(BlockReason(reason), detail))
        except ValueError:  # pragma: no cover - a reason this build cannot read
            continue
    return tuple(blocks)


def _fraction_or_none(text: str) -> Fraction | None:
    """Read a stored exact mark, or ``None`` when there is none."""
    return Fraction(text) if text else None


def _to_result(
    row: CandidateResult,
    display_name: str,
    stale: tuple[StaleReason, ...],
) -> StoredResult:
    return StoredResult(
        result_id=row.result_id,
        candidate_id=row.candidate_id,
        display_name=display_name,
        scan_id=row.scan_id,
        set_code=row.set_code,
        status=ResultStatus(row.status),
        answer_string=row.answer_string,
        machine_answer_string=row.machine_answer_string,
        corrected_questions=_load_numbers(row.corrected_questions),
        answer_key_id=row.answer_key_id,
        answer_key_revision=row.answer_key_revision,
        policy_id=row.policy_id,
        policy_revision=row.policy_revision,
        first_question=row.first_question,
        question_count=row.question_count,
        correct_count=row.correct_count,
        incorrect_count=row.incorrect_count,
        blank_count=row.blank_count,
        multiple_count=row.multiple_count,
        wrong_question_count=row.wrong_question_count,
        raw_score=_fraction_or_none(row.raw_score),
        final_score=_fraction_or_none(row.final_score),
        clamped=row.clamped,
        blocks=_parse_blocks(row.blocks),
        stale_reasons=stale,
        computed_at=row.computed_at,
        computed_by=row.computed_by,
    )


def list_results(
    database: ProjectDatabase,
    roster_id: int,
    batch_id: str,
    template: OmrTemplate | None = None,
    *,
    limit: int | None = None,
    offset: int = 0,
) -> tuple[StoredResult, ...]:
    """Return stored results with their staleness evaluated.

    ``template`` is optional: without it, staleness is judged on the key and
    policy revisions alone. With it, the candidate's *current* answers and set
    are recomputed and compared too, which is what catches a Phase 6 correction
    made since the batch was scored.
    """
    current = (
        gather_inputs(database, roster_id, batch_id, template)
        if template is not None
        else None
    )
    keys = verified_keys(database)
    policy = active_policy(database)
    names = {
        entry.candidate_id: entry.display_name
        for entry in reconciliation_store.list_entries(database, roster_id, batch_id)
    }
    by_id = (
        {entry.candidate_id: entry for entry in current.entries} if current else {}
    )

    with database.session() as session:
        statement = (
            select(CandidateResult)
            .where(CandidateResult.roster_id == roster_id)
            .where(CandidateResult.batch_id == batch_id)
            .order_by(CandidateResult.candidate_id)
        )
        if limit is not None:
            statement = statement.limit(limit).offset(offset)
        rows = session.scalars(statement).all()
        return tuple(
            _to_result(
                row,
                names.get(row.candidate_id, ""),
                stale_reasons_for(row, keys, policy, current, by_id.get(row.candidate_id)),
            )
            for row in rows
        )


def stale_reasons_for(
    row: CandidateResult,
    keys: dict[str, StoredKey],
    policy: StoredPolicy,
    current: BatchInputs | None,
    entry: ReconciliationEntry | None,
) -> tuple[StaleReason, ...]:
    """Say why a stored result no longer reflects its inputs.

    Compares what the result *was computed from* against what is current. A
    stale result keeps its number - it is still a true record of what the old
    inputs produced - but must not be presented as though it were current.

    **Only a result with a mark can be made stale by a rule change.** A blocked
    result has no mark to be out of date, and flagging it would bury the reason
    it was blocked under a second warning. An absent candidate has no mark
    either: a new key or a new penalty cannot change "did not sit the paper",
    and counting them as needing recomputation would fill the queue with work
    that changes nothing. Both can still go stale through *reconciliation* -
    the one input that can turn them into somebody with a script.

    A blocked result is the exception to the exception. It carries no mark, but
    it does carry a *claim* - "no verified answer key for Set C" - and that
    claim expires the moment somebody verifies the key. Left alone it would go
    on asserting a problem that has been fixed, which is a stale statement even
    though it is not a stale number. So its stored reasons are compared against
    the reasons it would be given now, and any difference makes it stale.
    """
    status = ResultStatus(row.status)
    if status is ResultStatus.BLOCKED:
        if current is None or entry is None:
            return ()
        outcome = score_candidate(inputs_for_candidate(current, entry))
        was = {item.reason for item in _parse_blocks(row.blocks)}
        now = {item.reason for item in outcome.blocks}
        return () if was == now else (StaleReason.INPUTS,)

    reasons: list[StaleReason] = []
    if status is ResultStatus.SCORED:
        if row.policy_id != policy.policy_id:
            reasons.append(StaleReason.SCORING_POLICY)
        stored_key = keys.get(row.set_code)
        if stored_key is None or stored_key.key_id != row.answer_key_id:
            reasons.append(StaleReason.ANSWER_KEY)

    if current is not None and entry is not None:
        now_absent = entry.effective_attendance is AttendanceState.ABSENT
        was_absent = status is ResultStatus.ABSENT
        if now_absent != was_absent:
            reasons.append(StaleReason.RECONCILIATION)
        scan_id, _ = working_script(entry)
        answers = current.answers.get(scan_id) if scan_id is not None else None
        if answers is not None and status is ResultStatus.SCORED:
            if answers.answers != row.answer_string:
                reasons.append(StaleReason.ANSWERS)
            if answers.set_code != row.set_code:
                reasons.append(StaleReason.SET_CODE)
    return tuple(dict.fromkeys(reasons))


def get_result(
    database: ProjectDatabase,
    roster_id: int,
    batch_id: str,
    candidate_id: str,
    template: OmrTemplate | None = None,
) -> StoredResult | None:
    """Return one candidate's stored result.

    Convenience for a single lookup. It reads the whole batch to evaluate
    staleness, so calling it per candidate is quadratic: anything iterating
    over a cohort - a report, a export - wants :func:`list_results` once.
    """
    found = [
        item
        for item in list_results(database, roster_id, batch_id, template)
        if item.candidate_id == candidate_id
    ]
    return found[0] if found else None


def breakdown_for(
    database: ProjectDatabase, result: StoredResult
) -> ScoreBreakdown | None:
    """Regenerate one result's per-question detail from its stored inputs.

    The detail is *not* stored - a million rows for a ten-thousand-candidate
    batch, every one of which could contradict the total. Rerunning the same
    pure function over the same stored inputs gives a breakdown that agrees
    with the mark by construction.
    """
    if result.answer_key_id is None or result.policy_id is None:
        return None
    stored_key = get_key(database, result.answer_key_id)
    stored_policy = get_policy(database, result.policy_id)
    if stored_key is None or stored_policy is None:
        return None
    if len(result.answer_string) != stored_key.key.question_count:
        return None
    return score_answers(
        result.answer_string,
        stored_key.key,
        stored_policy.policy,
        first_question=result.first_question,
    )


def count_results(
    database: ProjectDatabase,
    roster_id: int,
    batch_id: str,
    template: OmrTemplate | None = None,
) -> ResultCounts:
    """Summarise a batch's results."""
    return summarise(list_results(database, roster_id, batch_id, template))


def summarise(results: Sequence[StoredResult]) -> ResultCounts:
    """Summarise results already read.

    Split out from :func:`count_results` because a caller that has just listed
    a batch must not list it again to count it: reading ten thousand results
    twice to show one summary line is the whole batch's work done for nothing,
    and the two reads can disagree if anything changes between them.
    """
    by_set: dict[str, int] = {}
    for item in results:
        if item.status is ResultStatus.SCORED and item.set_code:
            by_set[item.set_code] = by_set.get(item.set_code, 0) + 1
    return ResultCounts(
        registered=len(results),
        scored=sum(1 for item in results if item.status is ResultStatus.SCORED),
        absent=sum(1 for item in results if item.status is ResultStatus.ABSENT),
        blocked=sum(1 for item in results if item.status is ResultStatus.BLOCKED),
        stale=sum(1 for item in results if item.is_stale),
        by_set=by_set,
    )


def clear_results(database: ProjectDatabase, roster_id: int, batch_id: str) -> int:
    """Delete a batch's results. Returns how many were removed.

    For starting again, not for tidying up: a result is evidence of what the
    stored inputs produced, and removing it removes the only record of a mark
    somebody may already have been told.
    """
    with database.session() as session:
        outcome = session.execute(
            delete(CandidateResult)
            .where(CandidateResult.roster_id == roster_id)
            .where(CandidateResult.batch_id == batch_id)
        )
        removed = int(getattr(outcome, "rowcount", 0) or 0)
    _LOGGER.info("Results cleared: roster=%d removed=%d", roster_id, removed)
    return removed

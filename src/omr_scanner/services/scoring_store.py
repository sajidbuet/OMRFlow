@dataclass(frozen=True, slots=True)
class BatchInputs:
    """Everything a batch needs to be scored, read once.

    Read once rather than per candidate: ten thousand candidates would
    otherwise open ten thousand transactions and decode ten thousand results
    that are already in memory.
    """

    plan: QuestionPlan
    entries: tuple[ReconciliationEntry, ...]
    results: dict[int, ScanResult]
    answers: dict[int, CandidateAnswers]
    keys: Mapping[str, StoredKey]
    """Verified keys by set code, compared canonically (:class:`SetCodeMap`)."""
    policy: StoredPolicy


def gather_inputs(
    database: ProjectDatabase,
    roster_id: int,
    batch_id: str,
    template: OmrTemplate,
) -> BatchInputs:
    """Read every authoritative input for a batch, once.

    The answers come through Phase 6's
    :func:`~omr_scanner.services.review_store.effective_answers` and
    :func:`~omr_scanner.services.review_store.effective_set_codes`, never from
    the recognition result alone: those hold what the *machine* read, and
    marking against them would ignore every correction a reviewer made.
    """
    batch_id = session_population.population_key(database, batch_id)
    plan = plan_for(template)
    entries = reconciliation_store.list_entries(database, roster_id, batch_id)
    # Only the session's effective sheets supply answers (0.1.1 phase 4): a
    # rejected, superseded, re-imported, excluded or deferred sheet, or one
    # in a batch read again as a whole, never does - even if something
    # upstream still named it: no answers, no mark. Each sheet's result,
    # reviewed answers and set come from its own batch, where they were
    # recorded, whichever batch of the session that is.
    population = session_population.population(database, batch_id)
    effective = population.effective
    results = session_population.results_by_scan(database, population, effective)
    decisions = session_population.effective_answers(database, population, template, effective)
    set_codes = session_population.effective_set_codes(database, population, effective)

    answers: dict[int, CandidateAnswers] = {}
    for scan_id, result in results.items():
        decided = decisions.get(scan_id)
        found = set_codes.get(scan_id)
        answers[scan_id] = build_candidate_answers(
            result,
            plan,
            scan_id=scan_id,
            decided=decided.decided if decided else None,
            unresolved=decided.unresolved_questions if decided else (),
            set_code=found.value if found else "",
        )

    return BatchInputs(
        plan=plan,
        entries=entries,
        results=results,
        answers=answers,
        keys=verified_keys(database),
        policy=active_policy(database),
    )


def scoring_rosters(database: ProjectDatabase) -> tuple[int, ...]:
    """Every active candidate list the batch is scored against, in set order.

    One per defined set that has attendance, in the operator's set order, then
    the project's unscoped list if it has one. A project that has defined its
    sets imports one list per set and has no unscoped list at all, so asking
    only for the unscoped one - as the Results stage once did - finds nothing,
    and a multi-set examination could never be marked. A project made before
    sets existed has only the unscoped list and is scored exactly as before.

    Each list is scored separately and each candidate is marked against the
    verified key for the set read from their own script, so a set's candidates
    never meet another set's key through this.
    """
    found: list[int] = []
    for exam_set in project_sets.list_sets(database):
        roster = reconciliation_store.active_roster(database, exam_set.set_id)
        if roster is not None and roster.roster_id not in found:
            found.append(roster.roster_id)
    unscoped = reconciliation_store.active_roster(database, None)
    if unscoped is not None and unscoped.roster_id not in found:
        found.append(unscoped.roster_id)
    return tuple(found)


@dataclass(frozen=True, slots=True)
class UnreconciledRoster:
    """A candidate list that has never been reconciled against the batch.

    Scoring such a pair finds no candidates at all - not blocked ones, none -
    so it has to be stopped with a reason rather than allowed to "succeed"
    with an empty table. The case that made this matter: a batch scanned
    while the Attendance stage still held the previous one, so every set was
    reconciled against the old batch and Results marked the new one.
    """

    roster_id: int
    label: str
    """``"Set 10"``, or ``"The candidate list"`` for an unscoped roster."""
    reconciled_batch_ids: tuple[str, ...]
    """The batches it *has* been reconciled against, most recent first."""

    def describe(self, batch_id: str) -> str:
        """One sentence naming the batch it needs and the one it has."""
        text = f"{self.label} has not been reconciled against batch {batch_id[:8]}"
        if self.reconciled_batch_ids:
            text += (
                " (it was last reconciled against batch "
                f"{self.reconciled_batch_ids[0][:8]})"
            )
        return text + ". Reconcile it on the Attendance stage."


def unreconciled_rosters(
    database: ProjectDatabase, roster_ids: Sequence[int], batch_id: str
) -> tuple[UnreconciledRoster, ...]:
    """The rosters among ``roster_ids`` with no reconciliation of ``batch_id``."""
    batch_id = session_population.population_key(database, batch_id)
    labels: dict[str | None, str] = {
        exam_set.set_id: exam_set.display_label
        for exam_set in project_sets.list_sets(database)
    }
    rosters = {
        roster.roster_id: roster for roster in reconciliation_store.list_rosters(database)
    }
    found: list[UnreconciledRoster] = []
    for roster_id in roster_ids:
        batches = reconciliation_store.reconciled_batch_ids(database, roster_id)
        if batch_id in batches:
            continue
        roster = rosters.get(roster_id)
        set_id = roster.set_id if roster is not None else None
        found.append(
            UnreconciledRoster(
                roster_id=roster_id,
                label=labels.get(set_id, "The candidate list"),
                reconciled_batch_ids=batches,
            )
        )
    return tuple(found)


def inputs_for_candidate(
    data: BatchInputs, entry: ReconciliationEntry
) -> ScoringInputs:
    """Assemble one candidate's scoring inputs from a batch's."""
    scan_id, _ = working_script(entry)
    answers = data.answers.get(scan_id) if scan_id is not None else None
    key = data.keys.get(answers.set_code) if answers and answers.set_code else None
    return ScoringInputs(
        entry=entry,
        answers=answers,
        key=key.key if key else None,
        policy=data.policy.policy,
        plan=data.plan,
    )


# ----------------------------------------------------------------------
# Scoring a batch
# ----------------------------------------------------------------------
def score_batch(
    database: ProjectDatabase,
    roster_id: int,
    batch_id: str,
    template: OmrTemplate,
    *,
    computed_by: str = "",
    candidates: Sequence[str] | None = None,
    should_cancel: Callable[[], bool] | None = None,
    on_progress: Callable[[int, int], None] | None = None,
) -> ResultCounts:
    """Score a batch - or the named candidates - from authoritative inputs.

    Args:
        database: The open project database.
        roster_id: The active candidate list.
        batch_id: The batch of scripts.
        template: The template the batch was read with.
        computed_by: Who ran the scoring, if known.
        candidates: Restrict to these candidate ids. ``None`` scores all of
            them.
        should_cancel: Polled between candidates.
        on_progress: Called with ``(done, total)``.

    Returns:
        The summary counts.

    **This is a recomputation, never a patch.** Every result is produced by
    running the scorer over the stored answer string, the stored set, the
    verified key and the active policy. No existing mark is read, adjusted or
    carried forward, so a corrupted stored score cannot survive a rescore - a
    property a test asserts directly by corrupting one.

    Results are written per candidate inside one transaction at the end, so a
    cancelled run leaves the previous results intact rather than a mixture.

    Raises:
        SetCollisionError: Two of the project's sets share one canonical code
            (legacy ``A`` and ``a``). Which key marks such a script cannot be
            decided, so nothing is scored until the operator renames one.
    """
    batch_id = session_population.population_key(database, batch_id)
    set_identity.require_no_collision(
        set_identity.load(database), purpose="Calculate Results"
    )
    data = gather_inputs(database, roster_id, batch_id, template)
    wanted = set(candidates) if candidates is not None else None
    targets = [
        entry
        for entry in data.entries
        if wanted is None or entry.candidate_id in wanted
    ]

    scored: list[tuple[ReconciliationEntry, CandidateScore]] = []
    total = len(targets)
    cancelled = False
    for index, entry in enumerate(targets, start=1):
        if should_cancel is not None and should_cancel():
            cancelled = True
            _LOGGER.info(
                "Scoring cancelled after %d of %d candidate(s); nothing written",
                index - 1,
                total,
            )
            break
        scored.append((entry, score_candidate(inputs_for_candidate(data, entry))))
        if on_progress is not None:
            on_progress(index, total)

    if cancelled:
        # Nothing is written. A half-marked batch under two policies, claiming
        # to be current, is worse than a batch that was never marked - and
        # "coherent after cancellation" is not something to approximate when
        # the numbers may end up on a transcript.
        return count_results(database, roster_id, batch_id)

    moment = _now()
    with database.session() as session:
        if wanted is None:
            _drop_vanished_blocked(session, roster_id, batch_id, data.entries)
        for entry, outcome in scored:
            _write_result(
                session,
                roster_id=roster_id,
                batch_id=batch_id,
                entry=entry,
                outcome=outcome,
                data=data,
                moment=moment,
                computed_by=computed_by,
            )

    counts = count_results(database, roster_id, batch_id)
    _LOGGER.info(
        "Scored: roster=%d candidates=%d scored=%d absent=%d blocked=%d policy_rev=%d",
        roster_id,
        len(scored),
        counts.scored,
        counts.absent,
        counts.blocked,
        data.policy.revision,
    )
    return counts


def _drop_vanished_blocked(
    session: Session,
    roster_id: int,
    batch_id: str,
    entries: Sequence[ReconciliationEntry],
) -> None:
    """Remove stored *blocked* results whose entry no longer exists.

    Such a row belongs to an unregistered ID that reconciliation no longer
    produces - its only sheet was rejected / excluded, deferred, or corrected
    to a registered candidate. It never carried a mark (an unregistered entry
    cannot be scored), so removing it removes no record of one; a row with a
    mark is never touched here.
    """
    current = {entry.candidate_id for entry in entries}
    for row in session.scalars(
        select(CandidateResult)
        .where(CandidateResult.roster_id == roster_id)
        .where(CandidateResult.batch_id == batch_id)
        .where(CandidateResult.status == ResultStatus.BLOCKED.value)
    ).all():
        if row.candidate_id not in current:
            session.delete(row)
    session.flush()


def _write_result(
    session: Session,
    *,
    roster_id: int,
    batch_id: str,
    entry: ReconciliationEntry,
    outcome: CandidateScore,
    data: BatchInputs,
    moment: datetime,
    computed_by: str,
) -> None:
    """Replace one candidate's stored result with a freshly computed one."""
    row = session.scalars(
        select(CandidateResult)
        .where(CandidateResult.roster_id == roster_id)
        .where(CandidateResult.batch_id == batch_id)
        .where(CandidateResult.candidate_id == entry.candidate_id)
        .limit(1)
    ).first()
    if row is None:
        row = CandidateResult(
            roster_id=roster_id,
            batch_id=batch_id,
            candidate_id=entry.candidate_id,
            created_at=moment,
            computed_at=moment,
        )
        session.add(row)

    answers = outcome.answers
    key_id = 0
    if outcome.key is not None:
        stored = data.keys.get(outcome.key.set_code)
        key_id = stored.key_id if stored else 0

    row.scan_id = answers.scan_id if answers else None
    row.set_code = outcome.set_code
    row.answer_string = answers.answers if answers else ""
    row.machine_answer_string = answers.machine_answers if answers else ""
    row.corrected_questions = _dump_numbers(answers.corrected) if answers else ""
    row.answer_key_id = key_id or None
    row.answer_key_revision = outcome.key.revision if outcome.key else 0
    row.policy_id = data.policy.policy_id
    row.policy_revision = data.policy.revision
    row.first_question = data.plan.first_question
    row.status = outcome.status.value
    row.blocks = "|".join(
        f"{item.reason.value}:{item.detail}" for item in outcome.blocks
    )
    row.stale_reasons = ""
    row.computed_at = moment
    row.computed_by = computed_by.strip()

    breakdown = outcome.breakdown
    if breakdown is not None:
        row.question_count = breakdown.question_count
        row.correct_count = breakdown.correct_count
        row.incorrect_count = breakdown.incorrect_count
        row.blank_count = breakdown.blank_count
        row.multiple_count = breakdown.multiple_count
        row.wrong_question_count = breakdown.wrong_question_count
        row.raw_score = str(breakdown.raw_score)
        row.final_score = str(breakdown.final_score)
        row.clamped = breakdown.clamped
    else:
        row.question_count = len(answers.answers) if answers else 0
        row.correct_count = row.incorrect_count = row.blank_count = 0
        row.multiple_count = row.wrong_question_count = 0
        row.raw_score = row.final_score = ""
        row.clamped = False


